import math

from . import circle, ellipse, ring, rect, poly, bar, arc, smooth, tube, frame, rotate_points, cut

R = rotate_points


def _rot(points, angle, cx=50.0, cy=50.0, r=0.0):
    """A rounded polygon rotated ``angle`` degrees clockwise about (cx, cy)."""
    return poly(R(points, angle, cx, cy), r)


def _rbar(x1, y1, x2, y2, w, angle, cx=50.0, cy=50.0, cap="round"):
    (a, b), (c, d) = R([(x1, y1), (x2, y2)], angle, cx, cy)
    return bar(a, b, c, d, w, cap)


def _clock_face(cx, cy, r, h1=(0, -0.62), h2=(0.48, 0.0), ticks=True):
    """Detail strings of a clock face: the face (cut from the case) with hands and ticks given back."""
    out = [circle(cx, cy, r)]
    out.append(cut(bar(cx, cy, cx + h1[0] * r, cy + h1[1] * r, max(2.6, r * 0.13))))
    out.append(cut(bar(cx, cy, cx + h2[0] * r, cy + h2[1] * r, max(2.6, r * 0.13))))
    out.append(cut(circle(cx, cy, max(2.4, r * 0.12))))
    if ticks:
        for a in (0, 90, 180, 270):
            p = R([(cx, cy - r * 0.86), (cx, cy - r * 0.68)], a, cx, cy)
            out.append(cut(bar(p[0][0], p[0][1], p[1][0], p[1][1], max(2.2, r * 0.09))))
    return out


def _dumpling():
    """Outline of a gyoza: flat bottom, pleated arched top, pointed ends."""
    pts = [(4, 72)]
    for i in range(1, 12):
        a = math.radians(180 + i * 15)
        r = 46 if i % 2 else 42
        pts.append((50 + r * math.cos(a), 74 + r * 0.95 * math.sin(a)))
    pts += [(96, 72), (88, 80), (50, 84), (12, 80)]
    return pts


def _recycle(cx, cy, s, w=None):
    """Three chasing arrows around (cx, cy), radius ``s``."""
    w = w if w is not None else s * 0.26
    out = []
    for k in range(3):
        a0 = -90 + k * 120 + 14
        a1 = a0 + 82
        out.append(arc(cx, cy, s, a0, a1, w, cap="butt"))
        t = math.radians(a1)
        tx, ty = cx + s * math.cos(t), cy + s * math.sin(t)
        nx, ny = math.cos(t), math.sin(t)                    # radial
        dx, dy = -math.sin(t), math.cos(t)                   # tangent (clockwise)
        hw = w * 1.15
        out.append(poly([(tx + nx * hw, ty + ny * hw), (tx - nx * hw, ty - ny * hw),
                         (tx + dx * w * 1.5, ty + dy * w * 1.5)], 0.6))
    return out


