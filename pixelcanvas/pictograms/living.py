def _ray(a, r0, r1, w, cx=50.0, cy=50.0):
    """A bar along the direction ``a`` degrees (0 = up, clockwise) from radius r0 to r1."""
    (x0, y0), (x1, y1) = R([(cx, cy - r0), (cx, cy - r1)], a, cx, cy)
    return bar(x0, y0, x1, y1, w)


def _branch(a, d, side, w, cx=50.0, cy=50.0, length=11.0):
    """A side branch of a snowflake arm: from distance ``d`` on arm ``a``, angled outwards to one ``side``."""
    (x0, y0), (x1, y1) = R([(cx, cy - d), (cx + side * length * 0.8, cy - d - length * 0.75)], a, cx, cy)
    return bar(x0, y0, x1, y1, w)


def _star(cx, cy, ro, ri, n=5, rot=-90.0, r=1.5):
    pts = []
    for i in range(2 * n):
        rr = ro if i % 2 == 0 else ri
        t = math.radians(rot + i * 180.0 / n)
        pts.append((cx + rr * math.cos(t), cy + rr * math.sin(t), r))
    return poly(pts)


def _petals(cx, cy, n, dist, rx, ry, rot=0.0):
    out = []
    for i in range(n):
        a = rot + i * 360.0 / n
        t = math.radians(a)
        out.append(ellipse(cx + dist * math.cos(t), cy + dist * math.sin(t), rx, ry, a))
    return out


def _cloud(dx=0.0, dy=0.0, k=1.0):
    def P(x, y):
        return 50 + (x - 50) * k + dx, 50 + (y - 50) * k + dy
    c = [circle(*P(30, 56), 16 * k), circle(*P(50, 44), 22 * k), circle(*P(71, 54), 17 * k),
         rect(*P(14, 56), 72 * k, 16 * k, 8 * k)]
    return c


def _spots(pts, rx=3.2, ry=2.4):
    return [ellipse(x, y, rx, ry, a) for x, y, a in pts]


def _finger(x, y0, y1, w=9.0):
    return rect(x - w / 2, y0, w, y1 - y0, w / 2)


