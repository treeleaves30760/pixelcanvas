def _rb(x1, y1, x2, y2, w, ang, cx=50.0, cy=50.0):
    (a, b), (c, d) = R([(x1, y1), (x2, y2)], ang, cx, cy)
    return bar(a, b, c, d, w)


def _rp(points, ang, r=0.0, cx=50.0, cy=50.0):
    return poly(R(points, ang, cx, cy), r)


def _re(cx, cy, rx, ry, rot, ang, pc=(50.0, 50.0)):
    """An ellipse whose centre is rotated about ``pc`` by ``ang`` degrees; ``rot`` is its own tilt."""
    (x, y), = R([(cx, cy)], ang, *pc)
    return ellipse(x, y, rx, ry, rot + ang)


