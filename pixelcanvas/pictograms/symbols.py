R = rotate_points


def _rot(points, angle, cx=50.0, cy=50.0, r=0.0):
    """A rounded polygon rotated ``angle`` degrees clockwise about (cx, cy)."""
    return poly(R(points, angle, cx, cy), r)


def _rbar(x1, y1, x2, y2, w, angle, cx=50.0, cy=50.0, cap="round"):
    (a, b), (c, d) = R([(x1, y1), (x2, y2)], angle, cx, cy)
    return bar(a, b, c, d, w, cap)


def _rrect(x, y, w, h, r, angle, cx=50.0, cy=50.0):
    """A rotated rectangle with rounded corners."""
    return _rot([(x, y, r), (x + w, y, r), (x + w, y + h, r), (x, y + h, r)], angle, cx, cy)


def _ering(cx, cy, rx, ry, w, rotate=0.0):
    """An elliptical band (outer ellipse with the inner one as a hole)."""
    return ellipse(cx, cy, rx, ry, rotate) + " " + reverse(ellipse(cx, cy, rx - w, ry - w, rotate))


def _ngon(cx, cy, r, n, rot=-90.0, rr=0.0):
    return poly([(cx + r * math.cos(math.radians(rot + i * 360.0 / n)),
                  cy + r * math.sin(math.radians(rot + i * 360.0 / n)), rr) for i in range(n)])


def _star(cx, cy, ro, ri, n=5, rot=-90.0, r=1.0):
    pts = []
    for i in range(2 * n):
        rr = ro if i % 2 == 0 else ri
        t = math.radians(rot + i * 180.0 / n)
        pts.append((cx + rr * math.cos(t), cy + rr * math.sin(t), r))
    return poly(pts)


def _gear(cx, cy, r, teeth, depth, hole, tw=0.5):
    """A gear outline (teeth of relative width ``tw``) with a round hole."""
    pts = []
    for i in range(teeth):
        a0 = 360.0 * i / teeth
        step = 360.0 / teeth
        for frac, rad in ((0.0, r - depth), (0.5 - tw / 2 - 0.06, r - depth), (0.5 - tw / 2, r),
                          (0.5 + tw / 2, r), (0.5 + tw / 2 + 0.06, r - depth)):
            t = math.radians(a0 + frac * step)
            pts.append((cx + rad * math.cos(t), cy + rad * math.sin(t), 1.0))
    return poly(pts) + " " + reverse(circle(cx, cy, hole))


def _wave_line(pts, w):
    return tube(pts, w)


def _arrowhead(tip, direction, size, r=1.5):
    """A triangle arrowhead at ``tip`` pointing along ``direction`` (degrees, 0 = right, 90 = down)."""
    t = math.radians(direction)
    dx, dy = math.cos(t), math.sin(t)
    nx, ny = -dy, dx
    bx, by = tip[0] - dx * size, tip[1] - dy * size
    return poly([(tip[0], tip[1], r), (bx + nx * size * 0.75, by + ny * size * 0.75, r),
                 (bx - nx * size * 0.75, by - ny * size * 0.75, r)])


