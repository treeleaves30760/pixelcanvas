def _wavy(cx, cy, r0, r1, n, phase=0.0, sy=1.0):
    """Closed outline points around (cx, cy) alternating between radius r0 and r1 (frilly leaf heads, clouds)."""
    pts = []
    for i in range(n * 2):
        a = phase + math.pi * i / n
        r = r1 if i % 2 == 0 else r0
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a) * sy))
    return pts


