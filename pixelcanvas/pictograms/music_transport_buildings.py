def _grid(x0, y0, cols, rows, w, h, dx, dy, r=1.2):
    return [rect(x0 + c * dx, y0 + r_ * dy, w, h, r) for r_ in range(rows) for c in range(cols)]


def _crenels(x0, x1, y, n, h=6):
    """Battlements: ``n`` merlons evenly spread on top of a wall from x0 to x1 at height y."""
    w = (x1 - x0) / (2 * n - 1)
    return [rect(x0 + i * 2 * w, y - h, w, h + 1) for i in range(n)]


def _cooling_tower(cx, top, w_top, w_waist, w_base, base=92):
    h = base - top
    return poly([(cx - w_top / 2, top), (cx + w_top / 2, top), (cx + w_waist / 2, top + h * 0.6),
                 (cx + w_base / 2, base), (cx - w_base / 2, base), (cx - w_waist / 2, top + h * 0.6)], 1.5)


