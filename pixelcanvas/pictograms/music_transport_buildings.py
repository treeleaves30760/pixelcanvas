def _wheels(outline, wheels, r=9.0, gap=2.6, radius=0.0):
    """A vehicle body: outline polygon, wheel arches cut ``gap`` around each wheel, then the wheels."""
    out = [poly(outline, radius) if not isinstance(outline, str) else outline]
    out += [cut(circle(x, y, r + gap)) for x, y in wheels]
    out += [circle(x, y, r) for x, y in wheels]
    return out


def _hubs(wheels, r=3.4):
    return [circle(x, y, r) for x, y in wheels]


def _rp(x, y, a=45):
    """One point rotated ``a`` degrees about the box centre."""
    return R([(x, y)], a)[0]


