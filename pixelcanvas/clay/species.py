def _option_names():
    keys = set(_QBASE) | set(_READ_BY_BUILDERS)
    for sp in SPECIES.values():
        keys |= set(sp)
        for c in (sp.get("coats") or {}).values():
            keys |= set(c)
    return sorted(keys - {"coats", "name", "material", "color"})


ANIMAL_OPTIONS = ["color"] + _option_names()


def _norm_species(name):
    """'Polar Bear' / 'polar-bear' / 'T-Rex' -> the registered spelling when there is one."""
    key = str(name).strip().lower().replace(" ", "_").replace("-", "_")
    for k in (key, key.replace("_", "")):
        if k in SPECIES:
            return k
    return name


def _species(name, coat=None):
    name = _norm_species(name)
    if name not in SPECIES:
        raise _unknown("animal", name, SPECIES, "Try clay.find('...') or clay.names('animal').")
    sp = dict(SPECIES[name])
    fam = sp.get("family", "quad")
    if fam == "quad":
        base = dict(_QBASE)
        base.update(sp)
        sp = base
    coats = sp.pop("coats", None) or {}
    if coat is not None:
        if isinstance(coat, str):
            if coat not in coats:
                raise _unknown(f"{name} coat", coat, coats, f"Coats: {', '.join(sorted(coats)) or '(none)'}.")
            sp.update(coats[coat])
        elif isinstance(coat, dict):
            sp.update(coat)
    sp["name"] = name
    return sp
